#!/usr/bin/env node

/**
 * Comprehensive Smoke Test Runner
 * Runs all smoke tests for WordPress migration verification
 */

const { execSync } = require('child_process')
const fs = require('fs')
const path = require('path')

console.log('🔥 Starting Comprehensive Smoke Tests for WordPress Migration')
console.log('=' .repeat(60))

// Check if the application is running
async function checkAppRunning() {
  try {
    const response = await fetch('http://localhost:3000/ar')
    if (response.status === 200) {
      console.log('✓ Application is running on localhost:3000')
      return true
    }
  } catch (error) {
    console.log('❌ Application is not running on localhost:3000')
    console.log('Please start the application with: npm run dev')
    return false
  }
}

// Run smoke tests
async function runSmokeTests() {
  const isRunning = await checkAppRunning()
  if (!isRunning) {
    process.exit(1)
  }

  console.log('\n📋 Running Smoke Tests...')
  
  try {
    // Run comprehensive smoke tests
    console.log('\n1. Running comprehensive page tests...')
    execSync('npx vitest run test/smoke/comprehensive-smoke-tests.test.ts --reporter=verbose', {
      stdio: 'inherit',
      env: { ...process.env, TEST_BASE_URL: 'http://localhost:3000' }
    })
    
    // Run revalidation tests
    console.log('\n2. Running revalidation tests...')
    execSync('npx vitest run test/smoke/revalidation-smoke-test.ts --reporter=verbose', {
      stdio: 'inherit',
      env: { ...process.env, TEST_BASE_URL: 'http://localhost:3000' }
    })
    
    console.log('\n✅ All smoke tests completed successfully!')
    
  } catch (error) {
    console.error('\n❌ Smoke tests failed:', error.message)
    process.exit(1)
  }
}

// Check WordPress connectivity
async function checkWordPressConnectivity() {
  console.log('\n🔌 Checking WordPress connectivity...')
  
  try {
    execSync('node scripts/check-wp-endpoints.js', { stdio: 'inherit' })
    console.log('✓ WordPress connectivity verified')
  } catch (error) {
    console.log('⚠️  WordPress connectivity issues detected')
    console.log('Please check your WordPress configuration')
  }
}

// Generate smoke test report
function generateSmokeTestReport() {
  const reportPath = 'test/smoke/SMOKE_TEST_REPORT.md'
  const timestamp = new Date().toISOString()
  
  const report = `# Smoke Test Report - WordPress Migration

**Generated:** ${timestamp}

## Test Summary

This report summarizes the comprehensive smoke tests run for the WordPress migration.

### Tests Executed

1. **Page Loading Tests**
   - Homepage with WordPress content
   - Article list page with pagination
   - Individual article pages with full content
   - Programs list page
   - Individual program pages with episodes
   - Author pages (if implemented)

2. **Content Workflow Tests**
   - Arabic RTL content rendering
   - Featured content display
   - Audio content handling

3. **Search and Navigation Tests**
   - Search functionality
   - Navigation between pages

4. **Error Handling Tests**
   - 404 page handling
   - Missing image handling

5. **Revalidation Tests**
   - Webhook revalidation triggers
   - Invalid request rejection
   - Cache behavior after revalidation

### WordPress Integration

- WordPress REST API connectivity
- ACF field exposure
- Custom post types accessibility
- Application Password authentication

### Performance Considerations

- Page load times
- Cache effectiveness
- Error handling gracefully

## Next Steps

After successful smoke tests:
1. Verify feature parity (Task 11.2)
2. Prepare rollback plan (Task 11.3)
3. Final performance verification (Task 11.4)

---
*Generated by WordPress Migration Smoke Test Suite*
`

  fs.writeFileSync(reportPath, report)
  console.log(`\n📄 Smoke test report generated: ${reportPath}`)
}

// Main execution
async function main() {
  try {
    await checkWordPressConnectivity()
    await runSmokeTests()
    generateSmokeTestReport()
    
    console.log('\n🎉 Smoke testing completed successfully!')
    console.log('All page types load correctly with WordPress content')
    console.log('Content workflows and revalidation triggers verified')
    
  } catch (error) {
    console.error('\n💥 Smoke testing failed:', error.message)
    process.exit(1)
  }
}

main()